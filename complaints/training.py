"""Data -> train-only CV -> validation cutoff -> one final test evaluation."""

import json
import platform
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.inspection import permutation_importance
from sklearn.metrics import fbeta_score, make_scorer
from sklearn.model_selection import StratifiedKFold, cross_validate, train_test_split

from complaints.data import file_hash
from complaints.evaluation import choose_threshold, metrics, wilson_interval
from complaints.features import FEATURES, TARGET, get_target, prepare_features
from complaints.models import candidates
from complaints.plots import save_figures


def train_project(root: Path, data_path: Path, seed: int = 42, min_recall: float = 0.85) -> dict:
    if not 0 < min_recall <= 1:
        raise ValueError("Minimum validation recall must be above 0 and at most 1.")
    raw = pd.read_csv(data_path)
    data = raw.drop_duplicates().reset_index(drop=True)
    if "ticket_id" not in data:
        data.insert(0, "ticket_id", [f"ROW-{i + 1:05d}" for i in range(len(data))])
    if data.ticket_id.isna().any() or data.ticket_id.duplicated().any():
        raise ValueError("Each training ticket_id must be present and unique. Resolve conflicting duplicates.")
    X = prepare_features(data)
    y = get_target(data)
    if len(data) < 100 or y.nunique() != 2 or y.value_counts().min() < 20:
        raise ValueError("Training needs at least 100 tickets and at least 20 examples of each class.")
    if not X.complaint_text.str.contains(r"[A-Za-z]{2,}").any():
        raise ValueError("Provide complaint text with words so TF-IDF can build a vocabulary.")

    indices = np.arange(len(data))
    train_idx, remaining = train_test_split(indices, test_size=0.4, stratify=y, random_state=seed)
    val_idx, test_idx = train_test_split(remaining, test_size=0.5, stratify=y.iloc[remaining], random_state=seed)
    X_train, y_train = X.iloc[train_idx], y.iloc[train_idx]
    X_val, y_val = X.iloc[val_idx], y.iloc[val_idx]
    X_test, y_test = X.iloc[test_idx], y.iloc[test_idx]

    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
    scoring = {"ap": "average_precision", "recall": "recall", "f2": make_scorer(fbeta_score, beta=2, zero_division=0)}
    models = candidates(seed)
    rows = []
    for name, pipeline in models.items():
        print(f"Training {name} ...", flush=True)
        folds = cross_validate(pipeline, X_train, y_train, cv=cv, scoring=scoring, n_jobs=1, error_score="raise")
        pipeline.fit(X_train, y_train)
        validation = metrics(y_val, pipeline.predict_proba(X_val)[:, 1], 0.5)
        row = {"model": name}
        for key in scoring:
            row[f"cv_{key}_mean"] = float(folds[f"test_{key}"].mean())
            row[f"cv_{key}_std"] = float(folds[f"test_{key}"].std(ddof=1))
        row.update({f"validation_{k}_at_0_5": validation[k] for k in ["accuracy", "precision", "recall", "f1", "roc_auc", "average_precision"]})
        rows.append(row)
    comparison = pd.DataFrame(rows).sort_values(["cv_ap_mean", "model"], ascending=[False, True]).reset_index(drop=True)
    selected = comparison.loc[comparison.model != "Dummy baseline", "model"].iloc[0]
    pipeline = models[selected]
    val_scores = pipeline.predict_proba(X_val)[:, 1]
    threshold, threshold_table = choose_threshold(y_val, val_scores, min_recall)
    validation = metrics(y_val, val_scores, threshold)

    # Model, preprocessing and cutoff are now frozen. No refit on validation/test.
    test_scores = pipeline.predict_proba(X_test)[:, 1]
    final = metrics(y_test, test_scores, threshold)
    final["recall_95ci"] = wilson_interval(final["tp"], final["tp"] + final["fn"])
    final["accuracy_95ci"] = wilson_interval(final["tp"] + final["tn"], final["rows"])
    baseline = metrics(y_test, models["Dummy baseline"].predict_proba(X_test)[:, 1], 0.5)
    perm = permutation_importance(pipeline, X_val, y_val, scoring="average_precision", n_repeats=5, random_state=seed, n_jobs=1)
    importance = pd.DataFrame({"feature": FEATURES, "importance_mean": perm.importances_mean, "importance_std": perm.importances_std})

    digest = file_hash(data_path)
    provenance = "user-supplied; source and label provenance not verified"
    manifest_path = data_path.parent / "dataset_manifest.json"
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest.get("sha256") == digest and manifest.get("kind") == "synthetic":
            provenance = "synthetic; generated by complaints/data.py; no real customers"
    metadata = {
        "schema_version": 1, "created_utc": datetime.now(timezone.utc).isoformat(),
        "seed": seed, "selected_model": selected, "threshold": threshold,
        "selection_rule": "Highest mean 5-fold training CV average precision; dummy excluded",
        "threshold_rule": "Highest validation F2 among thresholds meeting desired recall, otherwise highest F2",
        "desired_validation_recall": min_recall,
        "validation_recall_goal_met": bool(validation["recall"] >= min_recall),
        "data_provenance": provenance, "data_sha256": digest,
        "task": "Predict high-priority escalation proxy at first agent review",
        "target_note": "Priority proxy, not observed future escalation; confirm meaning for user-supplied labels",
        "features": FEATURES, "excluded": ["priority", TARGET, "customer_age", "customer_gender", "satisfaction_rating", "final_status", "ticket_id", "timestamps", "data_source"],
        "splits": {"train": len(train_idx), "validation": len(val_idx), "test": len(test_idx)},
        "split_method": "Stratified random 60/20/20; suitable for IID synthetic data only",
        "positive_share": float(y.mean()),
        "versions": {"python": platform.python_version(), "scikit-learn": sklearn.__version__, "numpy": np.__version__, "pandas": pd.__version__, "joblib": joblib.__version__},
    }
    report = {"metadata": metadata, "validation": validation, "test": final, "dummy_test_at_0_5": baseline}
    quality = {
        "raw_rows": len(raw), "clean_rows": len(data), "exact_duplicates_removed": len(raw) - len(data),
        "missing_safe_inputs": {k: int(v) for k, v in X.isna().sum().items()},
        "class_counts": {str(k): int(v) for k, v in y.value_counts().items()},
        "missing_policy": "Numeric medians and categorical Unknown fitted in each training fold; blank text gets a placeholder",
    }
    artifacts, reports = root / "artifacts", root / "reports"
    artifacts.mkdir(parents=True, exist_ok=True); reports.mkdir(parents=True, exist_ok=True)
    bundle = {"schema_version": 1, "features": FEATURES, "pipeline": pipeline, "threshold": threshold, "metadata": metadata}
    joblib.dump(bundle, artifacts / "model.joblib", compress=3)
    (artifacts / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    (reports / "metrics.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    (reports / "data_quality.json").write_text(json.dumps(quality, indent=2), encoding="utf-8")
    comparison.to_csv(reports / "model_comparison.csv", index=False)
    threshold_table.to_csv(reports / "validation_thresholds.csv", index=False)
    importance.to_csv(reports / "feature_importance.csv", index=False)
    split_manifest = data[["ticket_id"]].copy()
    split_manifest["split"] = ""
    for label, idx in [("train", train_idx), ("validation", val_idx), ("test", test_idx)]:
        split_manifest.loc[idx, "split"] = label
    split_manifest.to_csv(reports / "split_manifest.csv", index=False)
    for label, idx, scores in [("validation", val_idx, val_scores), ("test", test_idx, test_scores)]:
        predictions = data.iloc[idx][["ticket_id"] + FEATURES].copy()
        predictions["actual_proxy_label"] = y.iloc[idx].to_numpy()
        predictions["escalation_score"] = scores
        predictions["predicted_label"] = (scores >= threshold).astype(int)
        predictions.to_csv(reports / f"{label}_predictions.csv", index=False)
    save_figures(reports / "figures", y_test, test_scores, final, threshold_table, importance, comparison)
    summary = f"""# Measured run summary

Data: {provenance}. These scores are not evidence of real-world effectiveness.

- Selected model: **{selected}**, chosen using training CV average precision.
- Split: {len(train_idx)} train / {len(val_idx)} validation / {len(test_idx)} test.
- Validation-selected threshold: **{threshold:.2f}**; validation recall {validation['recall']:.1%}.
- Frozen test accuracy: **{final['accuracy']:.1%}**.
- Frozen test precision / recall / F1: **{final['precision']:.1%} / {final['recall']:.1%} / {final['f1']:.1%}**.
- Frozen test ROC-AUC / average precision: **{final['roc_auc']:.3f} / {final['average_precision']:.3f}**.
- Confusion counts: TN={final['tn']}, FP={final['fp']}, FN={final['fn']}, TP={final['tp']}.
- Approximate 95% recall interval: {final['recall_95ci'][0]:.1%} to {final['recall_95ci'][1]:.1%} (sampling only).
- Test positive share / no-skill AP: {final['positives'] / final['rows']:.1%}.

The pipeline stays fitted on the training partition. Validation selects the cutoff;
the final test set is evaluated only after those decisions. Do not tune on test errors.
ROC-AUC measures ranking; score percentages have not been calibrated on real tickets.
See docs/MODEL_CARD.md and reports/metrics.json for scope and limitations.
"""
    (reports / "RUN_SUMMARY.md").write_text(summary, encoding="utf-8")
    print(summary, flush=True)
    return report
